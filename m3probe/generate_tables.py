"""Generate fixed-point coefficients from the audition's parameter mappings."""
import json
from math import cos, exp, log, pi, tan
from pathlib import Path

SAMPLE_RATE = 44100
CUTOFF_STEPS = 64
Q_STEPS = 16
DECAY_MS = [round(150 * (1300 / 150) ** (step / 30)) for step in range(31)]
DEFINITION = json.loads(Path(__file__).with_name('definition.json').read_text())
PARAMETERS = {parameter['id']: parameter['mapping'] for parameter in DEFINITION['parameters']}


def q31(value):
    return max(-2**31, min(2**31 - 1, round(value * 2**31)))


def log_range(lower, upper, position):
    return lower * (upper / lower) ** position


def mapped(key, position):
    spec = PARAMETERS[key]
    return log_range(spec['minimum'], spec['maximum'], position)


def sweep(cutoff_step, q_step):
    cutoff = mapped('cutoff', cutoff_step / CUTOFF_STEPS)
    quality = mapped('resonance', q_step / Q_STEPS)
    g = tan(pi * cutoff / SAMPLE_RATE)
    damping = 1 / quality
    first = 1 / (1 + g * (g + damping))
    return [q31(first), q31(g * first), q31(g * g * first)]


def row(values):
    return '{' + ', '.join(map(str, values)) + '}'


def render():
    times = DECAY_MS + DECAY_MS[-1:]
    radii = [q31(exp(-1000 * log(1000) / (SAMPLE_RATE * ms))) for ms in times]
    note_cosine = [q31(cos(2 * pi * 440 * 2 ** ((note - 69) / 12) / SAMPLE_RATE))
                   for note in range(135)]
    lines = [
        '// Generated by generate_tables.py.',
        f'constexpr unsigned cutoff_steps = {CUTOFF_STEPS}, quality_steps = {Q_STEPS};',
        'struct SweepCoefficients { i32 a1, a2, a3; };',
        'constexpr unsigned decay_times[] = ' + row(times) + ';',
        'constexpr i32 radii[] = ' + row(radii) + ';',
        'constexpr i32 note_cosine[] = ' + row(note_cosine) + ';',
        'constexpr i32 half_damping[] = ' + row([
            q31(0.5 / mapped('resonance', step / Q_STEPS)) for step in range(Q_STEPS + 1)
        ]) + ';',
        'constexpr SweepCoefficients sweep_table[][quality_steps + 1] = {',
    ]
    for cutoff_step in range(CUTOFF_STEPS + 1):
        lines.append('    {')
        for q_step in range(Q_STEPS + 1):
            lines.append('        ' + row(sweep(cutoff_step, q_step)) + ',')
        lines.append('    },')
    lines.extend(['};', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    Path(__file__).with_name('coefficients.inc').write_text(render())
