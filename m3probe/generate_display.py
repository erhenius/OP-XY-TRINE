"""Generate the log-frequency grid and fixed-point lookup tables for the M3 display."""
from math import pi, tan
from pathlib import Path

HERE = Path(__file__).resolve().parent
GRID = 64
SAMPLE_RATE = 44100
FREQUENCIES = [45 * (14500 / 45) ** (i / GRID) for i in range(GRID + 1)]
AXIS = [50, 1000, 2000, 5000, 20000]
PLOT = [a * (b/a)**(i/8) for a,b in zip(AXIS, AXIS[1:]) for i in range(8)] + AXIS[-1:]
GAINS = [round(2048 * 10 ** (db / 10)) for db in range(-30, 19)]


def row(name, values):
    return f'constexpr unsigned {name}[] = {{' + ', '.join(map(str, values)) + '};\n'


(HERE / 'display_tables.inc').write_text(
    '// Generated by generate_display.py.\n'
    + row('hz_table', map(round, FREQUENCIES))
    + row('frequency_table', [round(2**20 * tan(pi * hz / SAMPLE_RATE)) for hz in FREQUENCIES])
    + row('plot_frequency', [round(2**20 * tan(pi * hz / SAMPLE_RATE)) for hz in PLOT])
    + row('damping_table', [round(1024 / (0.7 * (5 / 0.7) ** (i / 16))) for i in range(17)])
    + row('db_table', GAINS)
)
